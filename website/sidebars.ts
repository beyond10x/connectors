import {existsSync, readdirSync, readFileSync} from 'node:fs';
import path from 'node:path';
import type {SidebarsConfig} from '@docusaurus/plugin-content-docs';

const adaptersDir = path.join(__dirname, 'docs', 'reference', 'adapters');

const adapterSpecification = readdirSync(adaptersDir, {withFileTypes: true})
  .filter((entry) => entry.isDirectory())
  .map((entry) => {
    const dir = path.join(adaptersDir, entry.name);
    const category = JSON.parse(readFileSync(path.join(dir, '_category_.json'), 'utf8'));
    const parts = ['contracts', 'model'].filter((part) => existsSync(path.join(dir, part)));
    return {name: entry.name, label: category.label as string, position: category.position as number, parts};
  })
  .filter((adapter) => adapter.parts.length > 0)
  .sort((a, b) => a.position - b.position)
  .map((adapter) => ({
    type: 'category' as const,
    label: adapter.label,
    collapsed: true,
    items: adapter.parts.map((part) => ({
      type: 'autogenerated' as const,
      dirName: `reference/adapters/${adapter.name}/${part}`,
    })),
  }));

const sidebars: SidebarsConfig = {
  docsSidebar: [
    {
      type: 'category',
      label: 'Start here',
      collapsed: false,
      items: ['index', 'getting-started', 'status'],
    },
    {
      type: 'category',
      label: 'Connectors',
      collapsed: false,
      items: [{type: 'autogenerated', dirName: 'connectors'}],
    },
    {
      type: 'category',
      label: 'Concepts',
      collapsed: false,
      items: [{type: 'autogenerated', dirName: 'concepts'}],
    },
    {
      type: 'category',
      label: 'Guides',
      collapsed: false,
      items: [{type: 'autogenerated', dirName: 'guides'}],
    },
    {
      type: 'category',
      label: 'Examples',
      collapsed: false,
      items: [{type: 'autogenerated', dirName: 'examples'}],
    },
    {
      type: 'category',
      label: 'Reference',
      collapsed: true,
      items: [{type: 'autogenerated', dirName: 'reference'}],
    },
    {
      type: 'category',
      label: 'Specification',
      collapsed: true,
      items: [
        'concepts/contracts',
        'reference/crates',
        {type: 'doc', id: 'guides/build-a-catalog-bundle', label: 'Maintainers'},
        {type: 'autogenerated', dirName: 'reference/contracts'},
        ...adapterSpecification,
      ],
    },
  ],
};

export default sidebars;
